"""AI use-case inventory and proportionate risk tiering, following the structure of EIOPA's Opinion on AI governance
and risk management (EIOPA-BoS-25-360, 6 Aug 2025): impact assessment (3.2-3.4) -> proportionate measures (3.5-3.6).

This is a screening aid, not legal advice. The AI Act flag is a pointer to confirm with counsel."""
from dataclasses import dataclass, field

LEVELS = {"low": 0, "medium": 1, "high": 2}


@dataclass
class UseCase:
    id: str
    name: str
    purpose: str
    scale: str = "low"                       # volume of data/customers processed: low | medium | high
    personal_data: str = "none"              # none | personal | special (special = health, ids, financial identifiers)
    vulnerable_customers: bool = False
    autonomy: str = "low"                    # how far it acts without a human: low | medium | high
    customer_facing: bool = False
    decision_effect: str = "none"            # none | advisory | automated
    financial_inclusion_line: bool = False   # line important for inclusion or compulsory by law (EIOPA 3.3)
    prudential_impact: str = "low"           # effect on solvency / continuity / legal obligations (EIOPA 3.4)
    life_health_underwriting_or_pricing: bool = False   # AI Act Annex III pattern (see ai_act_flag)
    fraud_detection_only: bool = False
    owner: str = ""
    controls_in_place: list = field(default_factory=list)


@dataclass
class Assessment:
    use_case: str
    score: int
    tier: str
    ai_act_flag: str
    rationale: list
    required_controls: list
    gaps: list


CONTROLS = {
    "inventory": "Entry in the AI inventory with a named owner and documented purpose (3.2, 3.24)",
    "data_governance": "Data quality, representativeness and bias checks across the life cycle (3.14, 3.17-3.21)",
    "monitoring": "Performance metrics, drift and data-degradation monitoring (3.15, 3.36)",
    "redress": "Complaint and redress route for people harmed by the system (3.16)",
    "human_oversight": "Human review of outcomes proportionate to impact; override and fallback (3.5-3.6)",
    "explainability": "Outcomes meaningfully explainable for the audience that needs them (3.26)",
    "fairness_metrics": "Fairness/non-discrimination metrics chosen for the use case, with the actuarial-fairness caveat (3.15, Annex I)",
    "record_keeping": "Reviewed records: reasons for use, data, versions, tests, decisions (3.24, Annex I)",
    "robustness": "Resilience to data poisoning/adversarial input, API-connection testing, ICT fallback plan (3.37-3.38)",
}
TIER_CONTROLS = {
    "limited": ["inventory"],
    "standard": ["inventory", "data_governance", "monitoring", "redress"],
    "enhanced": list(CONTROLS),
}


def assess(uc: UseCase) -> Assessment:
    s, why = 0, []

    def add(points, reason):
        nonlocal s
        if points:
            s += points
            why.append(f"+{points} {reason}")
    add(LEVELS[uc.scale] , f"scale {uc.scale}")
    add({"none": 0, "personal": 1, "special": 2}[uc.personal_data], f"data: {uc.personal_data}")
    add(2 if uc.vulnerable_customers else 0, "vulnerable customers affected")
    add(LEVELS[uc.autonomy], f"autonomy {uc.autonomy}")
    add(1 if uc.customer_facing else 0, "customer-facing")
    add({"none": 0, "advisory": 1, "automated": 2}[uc.decision_effect], f"decision effect: {uc.decision_effect}")
    add(1 if uc.financial_inclusion_line else 0, "financial-inclusion or compulsory line")
    add(LEVELS[uc.prudential_impact], f"prudential impact {uc.prudential_impact}")
    tier = "enhanced" if s >= 8 else "standard" if s >= 4 else "limited"
    flag = ("likely high-risk under the EU AI Act (life/health risk assessment or pricing for natural persons): confirm scope, "
            "provider/deployer role and timing with counsel" if uc.life_health_underwriting_or_pricing and not uc.fraud_detection_only
            else "not flagged by this screen")
    required = TIER_CONTROLS[tier]
    gaps = [c for c in required if c not in uc.controls_in_place]
    return Assessment(uc.id, s, tier, flag, why, required, gaps)


def render_markdown(assessments, use_cases):
    by = {u.id: u for u in use_cases}
    L = ["# AI use-case inventory", "", "Generated by `tools/ai_inventory.py` from `docs/governance/use_cases.json`; do not edit.",
         "Screen based on the structure of EIOPA-BoS-25-360 (proportionate, risk-based). Not legal advice.", "",
         "| Use case | Tier | Score | Owner | Open control gaps | AI Act screen |", "|---|---|---|---|---|---|"]
    for a in assessments:
        u = by[a.use_case]
        L.append(f"| {u.id} {u.name} | {a.tier} | {a.score} | {u.owner or '-'} | {', '.join(a.gaps) or 'none'} | {a.ai_act_flag} |")
    L += ["", "## Control catalogue"] + [f"- **{k}**: {v}" for k, v in CONTROLS.items()]
    return "\n".join(L) + "\n"

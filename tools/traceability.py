#!/usr/bin/env python3
"""Backlog <-> test traceability gate.

Fails (exit 1) when: a story marked done has no test; a test references an unknown story; a Must story is
done with fewer than one test per acceptance criterion group (reported as a warning). Writes docs/product/TRACEABILITY.md.
"""
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent


def main():
    backlog = yaml.safe_load((ROOT / "docs/product/BACKLOG.yaml").read_text())["stories"]
    ids = {s["id"] for s in backlog}
    out = tempfile.mktemp(suffix=".json")
    env = {**os.environ, "TRACE_OUT": out}
    subprocess.run([sys.executable, "-m", "pytest", "--collect-only", "-q"], cwd=ROOT, env=env, capture_output=True, check=False)
    trace = json.loads(Path(out).read_text())
    errors, warns = [], []
    for sid in trace:
        if sid not in ids:
            errors.append(f"test references unknown story {sid}")
    for s in backlog:
        n = len(trace.get(s["id"], []))
        if s["status"] == "done" and n == 0:
            errors.append(f"{s['id']} is done but has no tests")
        if s["status"] == "done" and n < len(s["ac"]) and s["priority"] == "Must":
            warns.append(f"{s['id']}: {n} test(s) for {len(s['ac'])} acceptance criteria")
    L = ["# Traceability matrix", "", "Generated by `tools/traceability.py`; do not edit.", "",
         "| Story | Pri | Status | WSJF | Tests |", "|---|---|---|---|---|"]
    for s in sorted(backlog, key=lambda s: (s["status"] != "done", -((s["value"] + s["tc"] + s["rr"]) / s["size"]))):
        w = (s["value"] + s["tc"] + s["rr"]) / s["size"]
        L.append(f"| {s['id']} {s['title']} | {s['priority']} | {s['status']} | {w:.1f} | {len(trace.get(s['id'], []))} |")
    if warns:
        L += ["", "## Coverage warnings (fewer tests than acceptance criteria)"] + [f"- {w}" for w in warns]
    (ROOT / "docs/product/TRACEABILITY.md").write_text("\n".join(L) + "\n")
    done = [s for s in backlog if s["status"] == "done"]
    print(f"stories: {len(backlog)} ({len(done)} done), tests linked: {sum(len(v) for v in trace.values())}, warnings: {len(warns)}")
    for e in errors:
        print("ERROR", e)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
